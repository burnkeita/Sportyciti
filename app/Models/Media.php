<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Support\Facades\Storage;

class Media extends Model
{
    use HasFactory;

    protected $table = 'media';

    protected $fillable = [
        'title', 'disk', 'path', 'mime_type', 'size', 'width', 'height', 'variants',
        'alt_text', 'caption', 'credit', 'rights_confirmed', 'uploaded_by',
    ];

    protected function casts(): array
    {
        return [
            'variants' => 'array',
            'rights_confirmed' => 'boolean',
        ];
    }

    /** Responsive widths generated by OptimiseImage. */
    public const VARIANT_WIDTHS = ['sm' => 480, 'md' => 960, 'lg' => 1600];

    public function uploader(): BelongsTo
    {
        return $this->belongsTo(User::class, 'uploaded_by');
    }

    public function url(?string $variant = null): string
    {
        $path = $variant && isset($this->variants[$variant]) ? $this->variants[$variant] : $this->path;

        return Storage::disk($this->disk)->url($path);
    }

    public function srcset(): ?string
    {
        if (empty($this->variants)) {
            return null;
        }

        return collect(self::VARIANT_WIDTHS)
            ->filter(fn ($w, $key) => isset($this->variants[$key]))
            ->map(fn ($w, $key) => $this->url($key).' '.$w.'w')
            ->implode(', ');
    }

    public function isImage(): bool
    {
        return str_starts_with((string) $this->mime_type, 'image/');
    }

    public function altText(): string
    {
        return $this->alt_text ?: $this->title;
    }
}
